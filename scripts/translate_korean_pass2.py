# Second set of regex patterns
REGEX_FIXES = [
    # Dynamic day of week patterns
    (r'Every \$\{WEEKDAYS\[([^\]]+)\]\}요일', r'Every ${\1}'),
    (r'Every \$\{([^\}]+)\}요일', r'Every ${\1}'),
    (r'\$\{([^\}]+)\}요일', r'${\1}'),
    # 개 suffix in template literals
    (r'\$\{([^\}]+)\}개(?=[\s`\'",<{;)])', r'${\1}'),
    (r'(\{[^}]+\})개(?=\s*<)', r'\1'),
    # 일 count suffix  
    (r'\$\{([^\}]+)\}일(?=[\s`\'",<{;)>])', r'${\1} days'),
    # items suffix in counts (remaining from 건 → items)
    (r'\$\{([^\}]+)\}items(?=[\s`\'",<{;)>])', r'${\1}'),
    # 원 (currency unit after numbers)  
    (r'\(([^)]+)원\)', r'($\1)'),
]

def process_file(filepath: str) -> bool:
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
    except (UnicodeDecodeError, IOError):
        return False
    
    original = content
    
    # Apply regex fixes
    for pattern, replacement in REGEX_FIXES:
        content = re.sub(pattern, replacement, content)
    
    # Apply literal fixes
    for old, new in GARBLED_FIXES:
        content = content.replace(old, new)
    
    if content != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    return False


